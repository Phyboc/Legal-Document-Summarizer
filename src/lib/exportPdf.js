// Export a summary as a PDF without a PDF library: the browser lays the
// document out (which keeps Devanagari, Telugu and the other scripts correctly
// shaped) and its print dialog offers "Save as PDF".

const FONT_STACK =
  "'Newsreader', 'Noto Serif', 'Nirmala UI', 'Noto Sans Devanagari', 'Noto Sans Telugu', Georgia, serif";

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function buildSummaryDocument({
  docName,
  languageLabel,
  languageCode,
  summary,
  clauses,
  wordCount,
  generatedAt,
}) {
  const clauseMarkup = clauses
    .map(
      (clause) => `
        <li class="clause">
          <h2>${escapeHtml(clause.title)}</h2>
          <div class="pair">
            <div class="original">
              <span class="label">Original clause</span>
              <p>${escapeHtml(clause.original)}</p>
            </div>
            <div class="plain">
              <span class="label">Plain language</span>
              <p>${escapeHtml(clause.simplified)}</p>
            </div>
          </div>
        </li>`,
    )
    .join('');

  return `<!doctype html>
<html lang="${escapeHtml(languageCode || 'en')}">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(docName)} — Legal Lens</title>
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
<link href="https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,300..600;1,6..72,300..500&display=swap" rel="stylesheet" />
<style>
  @page { size: A4; margin: 16mm 15mm 16mm; }
  * { box-sizing: border-box; }
  body {
    margin: 0;
    font-family: ${FONT_STACK};
    font-size: 11pt;
    line-height: 1.5;
    color: #15160f;
    -webkit-print-color-adjust: exact;
    print-color-adjust: exact;
  }
  .brand {
    display: flex;
    justify-content: space-between;
    align-items: baseline;
    font-size: 9pt;
    color: #55584a;
    margin-bottom: 22pt;
  }
  .brand strong { font-size: 12pt; font-weight: 500; color: #15160f; }
  h1 { font-size: 26pt; font-weight: 500; line-height: 1.08; margin: 0 0 8pt; letter-spacing: -0.01em; }
  .meta { font-size: 9pt; color: #55584a; margin: 0 0 20pt; }
  .summary {
    background: #1e4436;
    color: #f2efe6;
    padding: 16pt 18pt;
    margin-bottom: 24pt;
  }
  .summary .label { color: rgba(242, 239, 230, 0.75); }
  .summary p { margin: 0; font-size: 12.5pt; line-height: 1.45; }
  .label {
    display: block;
    font-family: 'Public Sans', 'Nirmala UI', Arial, sans-serif;
    font-size: 8pt;
    letter-spacing: 0.02em;
    color: #55584a;
    margin-bottom: 3pt;
  }
  ol.clauses { list-style: none; margin: 0; padding: 0; }
  .clause { margin-bottom: 16pt; break-inside: avoid; }
  .clause h2 { font-size: 13pt; font-weight: 500; margin: 0 0 6pt; }
  .pair { display: table; width: 100%; border-spacing: 6pt 0; }
  .pair > div { display: table-cell; width: 50%; vertical-align: top; padding: 8pt 10pt; }
  .original { background: #f0ece0; }
  .plain { background: #e3e9d8; }
  .pair p { margin: 0; font-size: 10pt; line-height: 1.45; }
  .footer { margin-top: 22pt; font-size: 8.5pt; color: #55584a; }
  .footer p { margin: 0 0 4pt; }
</style>
</head>
<body>
  <div class="brand">
    <strong>Legal Lens</strong>
    <span>Plain-language document summary</span>
  </div>

  <h1>${escapeHtml(docName)}</h1>
  <p class="meta">
    ${escapeHtml(languageLabel || 'English')} · ${Number(wordCount || 0).toLocaleString('en-IN')} words ·
    ${clauses.length} ${clauses.length === 1 ? 'clause' : 'clauses'} · ${escapeHtml(generatedAt)}
  </p>

  <div class="summary">
    <span class="label">Summary</span>
    <p>${escapeHtml(summary)}</p>
  </div>

  <ol class="clauses">${clauseMarkup}</ol>

  <div class="footer">
    <p>Legal Lens explains documents for general understanding. It is not legal advice, and it does not replace a qualified lawyer.</p>
    <p>Generated by Legal Lens · ${escapeHtml(generatedAt)}</p>
  </div>
</body>
</html>`;
}

export function exportSummaryPdf(details) {
  if (typeof document === 'undefined') return false;

  const html = buildSummaryDocument(details);
  const frame = document.createElement('iframe');
  frame.setAttribute('aria-hidden', 'true');
  frame.setAttribute('title', 'Printable summary');
  frame.style.cssText = 'position:fixed;left:-10000px;top:0;width:794px;height:1123px;border:0;';
  document.body.appendChild(frame);

  const win = frame.contentWindow;
  const doc = win.document;
  doc.open();
  doc.write(html);
  doc.close();

  const cleanup = () => {
    window.setTimeout(() => {
      if (frame.parentNode) frame.parentNode.removeChild(frame);
    }, 1000);
  };

  const print = () => {
    try {
      win.focus();
      win.print();
    } finally {
      cleanup();
    }
  };

  const fontsReady = doc.fonts && doc.fonts.ready ? doc.fonts.ready : Promise.resolve();
  Promise.race([fontsReady, new Promise((resolve) => window.setTimeout(resolve, 1200))]).then(() => {
    window.setTimeout(print, 120);
  });

  return true;
}
